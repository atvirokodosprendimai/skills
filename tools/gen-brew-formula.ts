#!/usr/bin/env -S deno run -A
/**
 * gen-brew-formula.ts — the canonical AKS brew formula generator.
 *
 * ONE way an AKS release reaches atvirokodosprendimai/homebrew-tap:
 *   gen-brew-formula.ts <owner>/<repo> <tag> [binary]
 *
 * Rules that make it canonical:
 * - The formula ALWAYS serves the prebuilt release archive from the GitHub
 *   release, never a source build: a version-stamped binary must print its
 *   tag, and a source build that fails to stamp it silently breaks the
 *   repo's UPDATE verification step (see tool-multipathreadwrite UPDATE.md).
 * - The sha256 is taken from the release's own SHA256SUMS.txt, never
 *   recomputed from a re-download: the formula attests what was published.
 * - The rendered Ruby mirrors the GoReleaser formula shape already in the
 *   tap (wgmesh.rb): per-OS/arch url+sha256 pairs, a minimal install and a
 *   version test. No bottles, no livecheck — tap formulas ship source
 * *-free* and brew audits the shape as-is.
 * - Pure function core (renderFormula) + thin fetch CLI, so CI can run it
 *   unattended at release time and tests can drive the renderer offline.
 *
 * Usage: deno run -A gen-brew-formula.ts atvirokodosprendimai/tool-multipathreadwrite v1.75.0 mrw
 */

const USER = "atvirokodosprendimai";

interface Target {
  goos: "darwin" | "linux";
  goarch: "amd64" | "arm64";
}

export const TARGETS: Target[] = [
  { goos: "darwin", goarch: "amd64" },
  { goos: "darwin", goarch: "arm64" },
  { goos: "linux", goarch: "amd64" },
  { goos: "linux", goarch: "arm64" },
];

export interface FormulaInput {
  repo: string; // "owner/name"
  tag: string; // "v1.75.0"
  binary: string; // "mrw"
  description: string;
  homepage?: string;
  license?: string;
  /** release archive basename, e.g. mrw_darwin_arm64.tar.gz (mrw ships NO version in archive names) */
  archiveName?: (t: Target, binary: string) => string;
  /** checksums keyed by archive basename, from the release SHA256SUMS.txt */
  checksums: Record<string, string>;
  /** extra ruby lines for each install block (dirs etc.); default none */
  installExtra?: string[];
  testBlock?: string[];
}

/** mrw's convention (ci.yml): mrw_<goos>_<goarch>.tar.gz, no version. */
export const defaultArchiveName = (t: Target, binary: string): string =>
  `${binary}_${t.goos}_${t.goarch}.tar.gz`;

export function renderFormula(input: FormulaInput): string {
  const { repo, tag, binary, description, checksums } = input;
  const homepage = input.homepage ?? `https://github.com/${repo}`;
  const license = input.license ?? "MIT";
  const archName = (t: Target) => (t.goarch === "amd64" ? "intel" : "arm");
  const url = (t: Target) => {
    const an = (input.archiveName ?? defaultArchiveName)(t, binary);
    return `https://github.com/${repo}/releases/download/${tag}/${an}`;
  };
  const sha = (t: Target) => {
    const an = (input.archiveName ?? defaultArchiveName)(t, binary);
    const s = checksums[an];
    if (!s) throw new Error(`missing checksum for ${an} — release incomplete?`);
    return s;
  };

  const pad = (n: number) => "  ".repeat(n);
  const block = (t: Target, depth: number, cond: string | null): string => {
    const inner = [
      `url "${url(t)}"`,
      `sha256 "${sha(t)}"`,
      `define_method(:install) do`,
      `  bin.install "${binary}"`,
      ...(input.installExtra ?? []).map((l) => `  ${l}`),
      `end`,
    ]
      .map((l) => `${pad(depth + 1)}${l}`)
      .join("\n");
    return cond ? `${pad(depth)}if ${cond}\n${inner}\n${pad(depth)}end` : inner;
  };

  const mac = TARGETS.filter((t) => t.goos === "darwin")
    .map((t) => block(t, 2, `Hardware::CPU.${archName(t)}?`))
    .join("\n");
  const linux = TARGETS.filter((t) => t.goos === "linux")
    .map((t) => block(t, 2, `Hardware::CPU.${archName(t)}? && Hardware::CPU.is_64_bit?`))
    .join("\n");
  const test = (input.testBlock ?? [`system "#{bin}/${binary}", "version"`])
    .map((l) => `${pad(2)}${l}`)
    .join("\n");
  const cls = binary[0].toUpperCase() + binary.slice(1);

  return `# typed: false
# frozen_string_literal: true

# Generated by AKS gen-brew-formula.ts for ${repo} ${tag}. DO NOT EDIT.
# Regenerate on every release; a stale formula serves a stale sha.
class ${cls} < Formula
  desc "${description}"
  homepage "${homepage}"
  version "${tag.replace(/^v/, "")}"
  license "${license}"

  on_macos do
${mac}
  end

  on_linux do
${linux}
  end

  test do
${test}
  end
end`;

}

