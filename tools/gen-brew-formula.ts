// ---------- CLI ----------

async function fetchText(url: string): Promise<string> {
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${res.status} ${url}`);
  return res.text();
}

export async function parseChecksums(repo: string, tag: string): Promise<Record<string, string>> {
  const text = await fetchText(
    `https://github.com/${repo}/releases/download/${tag}/SHA256SUMS.txt`,
  );
  const map: Record<string, string> = {};
  for (const l of text.split("\n")) {
    const m = l.match(/^([0-9a-f]{64})\s+\*?(.+)$/);
    if (m) map[m[2].trim()] = m[1];
  }
  return map;
}

if (import.meta.main) {
  const [repo, tag, binaryArg, descArg] = Deno.args;
  const binary = binaryArg ?? repo?.split("/")[1]?.split("-").pop() ?? "";
  if (!repo || !tag || repo.split("/").length !== 2 || !/^v\d+\.\d+\.\d+$/.test(tag) || !binary) {
    console.error(
      "usage: gen-brew-formula.ts <owner>/<repo> <vX.Y.Z> [binary] [description]\n" +
        "example: gen-brew-formula.ts atvirokodosprendimai/tool-multipathreadwrite v1.75.0 mrw",
    );
    Deno.exit(2);
  }
  const checksums = await parseChecksums(repo, tag);
  const formula = renderFormula({ repo, tag, binary, description: descArg ?? "", checksums });
  console.log(formula);
}
